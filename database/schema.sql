-- Bantay Barangay schema (ERD + group-approved changes)
-- Changes: roles table (users.role_id FK), barangay_code is the barangays primary key,
-- activity_barangays table, activities.is_public, one submission per barangay per period.
-- Target: PostgreSQL 14+ (Neon). Same tables, columns, PKs and FKs as the MySQL version.
-- Added for the serverless (Vercel) version: file_store (uploaded files) and login_attempts (login lockout).
-- Times are stored as Philippine local time (Asia/Manila) in plain TIMESTAMP columns.
-- Run this file once on an empty database.

-- ---------------------------------------------------------------
-- ROLES (reference data). Created first because USERS, ANNOUNCEMENTS
-- and IMPORTANT_DATES point to it.
-- ---------------------------------------------------------------
CREATE TABLE roles (
  role_id        INT GENERATED BY DEFAULT AS IDENTITY,
  role_name      VARCHAR(30)  NOT NULL,
  description    VARCHAR(255) NULL,
  date_created   TIMESTAMP    NOT NULL DEFAULT (NOW() AT TIME ZONE 'Asia/Manila'),
  PRIMARY KEY (role_id),
  CONSTRAINT uq_roles_name UNIQUE (role_name)
);

