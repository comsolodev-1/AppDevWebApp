-- ---------------------------------------------------------------
-- Group-approved addition: which barangays an activity is assigned to
-- ---------------------------------------------------------------
CREATE TABLE activity_barangays (
  activity_id  INT NOT NULL,
  barangay_code VARCHAR(20) NOT NULL,
  PRIMARY KEY (activity_id, barangay_code),
  CONSTRAINT fk_ab_activity
    FOREIGN KEY (activity_id) REFERENCES activities (activity_id)
    ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT fk_ab_barangay
    FOREIGN KEY (barangay_code) REFERENCES barangays (barangay_code)
    ON DELETE CASCADE ON UPDATE CASCADE
);

-- ---------------------------------------------------------------
-- Readable view: who submitted and who confirmed each submission
-- ---------------------------------------------------------------
CREATE VIEW v_submission_details AS
SELECT s.date_id AS submission_id,
       s.barangay_code,
       b.barangay_name,
       a.activity_name,
       p.period_name,
       s.submission_status,
       s.is_late,
       s.score,
       s.date_submitted,
       s.submitted_by,
       su.first_name || ' ' || su.last_name AS submitted_by_name,
       sr.role_name AS submitted_by_role,
       s.confirmed_by,
       cu.first_name || ' ' || cu.last_name AS confirmed_by_name,
       cr.role_name AS confirmed_by_role,
       s.confirmation_date
FROM submissions s
JOIN barangays b ON b.barangay_code = s.barangay_code
JOIN reporting_period p ON p.period_id = s.period_id
JOIN activities a ON a.activity_id = p.activity_id
JOIN users su ON su.user_id = s.submitted_by
JOIN roles sr ON sr.role_id = su.role_id
LEFT JOIN users cu ON cu.user_id = s.confirmed_by
LEFT JOIN roles cr ON cr.role_id = cu.role_id;

CREATE INDEX ix_submissions_submitted_by ON submissions (submitted_by);
CREATE INDEX ix_submissions_confirmed_by ON submissions (confirmed_by);

-- ---------------------------------------------------------------
-- Serverless workarounds
-- file_store: uploaded files live here instead of on a disk (Vercel has no permanent disk).
--   The *_path columns (file_path, denial_attachment, template_link, attachment_file_path)
--   hold the key of the file in this table, e.g. 'submissions/3f9c...pdf'.
-- login_attempts: failed-login counter for the 15 minute lockout (memory is not shared between serverless calls).
-- ---------------------------------------------------------------
CREATE TABLE file_store (
  file_key     VARCHAR(255) NOT NULL,
  content      BYTEA        NOT NULL,
  date_created TIMESTAMP    NOT NULL DEFAULT (NOW() AT TIME ZONE 'Asia/Manila'),
  PRIMARY KEY (file_key)
);

CREATE TABLE login_attempts (
  attempt_key  VARCHAR(255) NOT NULL,
  attempts     INT          NOT NULL,
  expires_at   TIMESTAMPTZ  NOT NULL,
  PRIMARY KEY (attempt_key)
);
